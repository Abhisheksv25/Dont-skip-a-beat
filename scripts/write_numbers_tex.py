"""
write_numbers_tex.py -- turn results/m1_stats.json into LaTeX macros (paper/milestone1/numbers.tex),
so every number in the paper comes straight from the code and nothing is typed by hand.

    python scripts/write_numbers_tex.py
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument("--stats", default=os.path.join(ROOT, "results", "m1_stats.json"))
ap.add_argument("--out", default=os.path.join(ROOT, "paper", "milestone1", "numbers.tex"))
args = ap.parse_args()
S = json.load(open(args.stats))
out = []


def put(name, value):
    out.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def n(v):
    return f"{int(round(v)):,}".replace(",", "{,}")


def pct(v, d=1):
    return f"{v:.{d}f}\\%"


def pct_small(v):
    return pct(v, 2) if v < 1 else pct(v, 1)


W = {"N": "N", "S": "S", "V": "V", "F": "F", "Q": "Q"}
for split, tag in [("DS1", "One"), ("DS2", "Two")]:
    sp = S["splits"][split]
    put(f"DS{tag}Total", n(sp["total"]))
    for k in "NSVFQ":
        put(f"DS{tag}{k}", n(sp["counts"][k]))
        put(f"DS{tag}{k}pct", pct_small(sp["pct"][k]))
    for k in "SVF":
        c = sp["concentration"][k]
        put(f"DS{tag}{k}topRec", c["top_record"])
        put(f"DS{tag}{k}topShare", pct(c["top_share_pct"], 0))
        put(f"DS{tag}{k}topThreeShare", pct(c["top3_share_pct"], 0))
        put(f"DS{tag}{k}nRecAny", c["n_records_with_any"])
        put(f"DS{tag}{k}nRecTen", c["n_records_with_10plus"])

put("nBeatAnnAll", n(S["n_beat_annotations_all48"]))
put("nExtractedOne", n(S["n_extracted_DS1"]))
put("nExtractedTwo", n(S["n_extracted_DS2"]))
put("ratioNF", n(S["imbalance_ratio_N_to_F_DS1"]))
put("budgetTenS", n(S["random_budget_for_10_examples"]["S"]))
put("budgetTenV", n(S["random_budget_for_10_examples"]["V"]))
put("budgetTenF", n(S["random_budget_for_10_examples"]["F"]))
put("expFiveHundredS", f"{S['expected_in_500_random']['S']:.1f}")
put("expFiveHundredF", f"{S['expected_in_500_random']['F']:.1f}")
put("budgetFortyPct", n(S["budget_40pct_DS1"]))
for k in "NSVF":
    r = S["rr_DS1"][k]
    put(f"rrMed{k}", f"{r['rr_ratio_median']:.2f}")
    put(f"rrBelow{k}", pct(100 * r["frac_rr_ratio_below_0.9"], 0))
put("pcaNinety", S["pca_components_for"]["90"])
put("pcaNinetyFive", S["pca_components_for"]["95"])
put("pcaNinetyNine", S["pca_components_for"]["99"])
pid = S["patient_id_from_normal_beat"]
put("pidAcc", pct(100 * pid["accuracy_mean"], 0))
put("pidChance", pct(100 * pid["chance_majority"], 0))
put("pidNpat", pid["n_patients"])
L = S["leakage_check_1nn"]
for split, tag in [("random_beat_split", "Rand"), ("patient_split_DS1_to_DS2", "Pat")]:
    put(f"leak{tag}F", f"{L[split]['macro_f1']:.2f}")
    for k in "SVF":
        put(f"leak{tag}Sens{k}", f"{L[split]['sens_' + k]:.2f}")
sb = L["patient_split_S_breakdown"]
put("missedSasN", pct(100 * sb["missed_S_called_N"], 0))
put("sensStop", pct(100 * sb["sens_S_top_record"], 0))
put("sensSother", pct(100 * sb["sens_S_other_records"], 0))
put("stripRec", S["strip"]["record"])
put("hrLo", n(S["median_heart_rate_bpm_range_over_records"][0]))
put("hrHi", n(S["median_heart_rate_bpm_range_over_records"][1]))
put("tsneN", n(sum(S["tsne_points"].values())))

for k in "NSVF":
    put(f"rrLongMed{k}", f"{S['rr_DS1'][k]['rr_ratio_long_median']:.2f}")
    put(f"rrLongBelow{k}", pct(100 * S['rr_DS1'][k]['frac_rr_ratio_long_below_0.9'], 0))
sl = S["S_not_premature_local"]
put("sLateFrac", pct(100 * sl["frac_of_S"], 0))
put("sLateFollowS", pct(100 * sl["frac_following_S"], 0))
put("sLatePremLong", pct(100 * sl["frac_premature_vs_long_baseline"], 0))
nb = S["neighbour_purity_pca30"]
put("nbrSamePatient", pct(100 * nb["same_patient"], 0))
put("nbrSameClass", pct(100 * nb["same_class"], 0))
put("nbrSamePatientS", pct(100 * nb["same_patient_S"], 0))
put("chanceUniformPatient", pct(100 / pid["n_patients"], 1))
put("nbrChancePatient", pct(100 * nb["chance_same_patient"], 0))
put("nbrChanceClass", pct(100 * nb["chance_same_class"], 0))
fc = S["F_context"]
put("fRRpost", f"{fc['median_rr_post_s']:.2f}")
put("nRRpost", f"{fc['N_median_rr_post_s']:.2f}")
put("pcaEighty", S["pca_components_for"]["80"])
put("nQTotal", n(S["splits"]["DS1"]["counts"]["Q"] + S["splits"]["DS2"]["counts"]["Q"]))
put("ratioSTwoOne", f"{S['splits']['DS2']['counts']['S'] / S['splits']['DS1']['counts']['S']:.1f}")
path = args.out
with open(path, "w") as f:
    f.write("% Auto-generated by scripts/write_numbers_tex.py from results/m1_stats.json. Do not edit.\n")
    f.write("\n".join(out) + "\n")
print("wrote", path, len(out), "macros")
